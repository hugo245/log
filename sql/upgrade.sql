-- =========================================================================================
--  Studio Panel: upgrade an existing database to this version
--
--  Safe to run on a live database, and safe to run more than once. It never deletes data.
--  Run it in the Supabase SQL editor after updating the code, before restarting the API.
--
--  What it does:
--    1. Adds app_settings.branding (Settings > Branding saves here)
--    2. Gives the starter roles the new permissions (Edit branding, revenue share,
--       contracts, tax details) and adds the tables for notifications, revenue share,
--       contracts, tax forms and two-factor sign-in
--    3. Re-applies the database lock-down to any table it adds
-- =========================================================================================

begin;

-- 1. Branding column ---------------------------------------------------------------------
alter table public.app_settings
    add column if not exists branding jsonb not null default '{}'::jsonb;

-- 2. New permission for the starter Owner and Admin roles ------------------------------------
update public.roles
set permissions = permissions || '["settings.manage_branding"]'::jsonb
where name in ('Owner', 'Admin')
  and not permissions ? 'settings.manage_branding';

update public.roles set permissions = permissions || '["revenue.manage"]'::jsonb
where name in ('Owner', 'Admin') and not permissions ? 'revenue.manage';
update public.roles set permissions = permissions || '["contracts.manage"]'::jsonb
where name in ('Owner', 'Admin', 'Manager') and not permissions ? 'contracts.manage';
update public.roles set permissions = permissions || '["tax.view"]'::jsonb
where name = 'Owner' and not permissions ? 'tax.view';

-- 2b. New features (notifications, revenue share, contracts, tax forms, two-factor sign-in) --
-- >>> features schema (generated from one source; keep setup.sql and upgrade.sql in step)
-- Notifications -----------------------------------------------------------------------------
create table if not exists public.notifications (
    id                 bigint generated by default as identity primary key,
    roblox_user_id     bigint not null,
    kind               text not null default 'general',
    title              text not null,
    body               text,
    link               text,
    read_at            timestamptz,
    created_at         timestamptz not null default now()
);
create index if not exists notifications_user_idx on public.notifications (roblox_user_id, created_at desc);

create table if not exists public.notify_prefs (
    roblox_user_id     bigint primary key,
    email              text,
    email_verified     boolean not null default false,
    email_enabled      boolean not null default true,
    email_code_hash    text,
    email_code_expires timestamptz,
    updated_at         timestamptz not null default now()
);

alter table public.app_settings add column if not exists notify_webhook_url text;
alter table public.app_settings add column if not exists notify_webhook_events jsonb;

-- Revenue share -----------------------------------------------------------------------------
create table if not exists public.revenue_shares (
    id                 bigint generated by default as identity primary key,
    game_id            bigint not null,
    roblox_user_id     bigint not null,
    roblox_username    text,
    percent            numeric not null check (percent > 0 and percent <= 100),
    note               text,
    active             boolean not null default true,
    created_by         text,
    created_at         timestamptz not null default now()
);
create index if not exists revenue_shares_game_idx on public.revenue_shares (game_id) where active;
create index if not exists revenue_shares_user_idx on public.revenue_shares (roblox_user_id);

create table if not exists public.revenue_periods (
    id                   bigint generated by default as identity primary key,
    game_id              bigint not null,
    period               text not null check (period ~ '^[0-9]{4}-[0-9]{2}$'),
    revenue              numeric not null check (revenue > 0),
    currency             text not null default 'ROBUX',
    note                 text,
    recorded_by          text,
    recorded_by_user_id  bigint,
    request_ids          jsonb not null default '[]'::jsonb,
    created_at           timestamptz not null default now(),
    unique (game_id, period)
);

-- Contracts ---------------------------------------------------------------------------------
create table if not exists public.contracts (
    id                  bigint generated by default as identity primary key,
    title               text not null,
    roblox_user_id      bigint not null,
    roblox_username     text,
    game_id             bigint,
    currency            text not null default 'ROBUX',
    terms               text,
    status              text not null default 'draft' check (status in ('draft', 'sent', 'active', 'completed', 'cancelled')),
    due_at              timestamptz,
    created_by          text,
    created_by_user_id  bigint,
    created_at          timestamptz not null default now(),
    sent_at             timestamptz,
    signed_at           timestamptz,
    signed_name         text,
    signed_meta         jsonb,
    completed_at        timestamptz,
    cancelled_at        timestamptz,
    cancel_reason       text
);
create index if not exists contracts_user_idx on public.contracts (roblox_user_id);
create index if not exists contracts_status_idx on public.contracts (status);

create table if not exists public.contract_milestones (
    id                  bigint generated by default as identity primary key,
    contract_id         bigint not null references public.contracts (id) on delete cascade,
    position            integer not null default 0,
    title               text not null,
    details             text,
    amount              numeric not null check (amount > 0),
    due_at              timestamptz,
    status              text not null default 'open' check (status in ('open', 'submitted', 'approved')),
    submitted_at        timestamptz,
    submitted_note      text,
    decided_at          timestamptz,
    decided_by          text,
    decision_note       text,
    payment_request_id  text
);
create index if not exists contract_milestones_contract_idx on public.contract_milestones (contract_id);

-- Tax details -------------------------------------------------------------------------------
-- Tax IDs and dates of birth are encrypted by the API (TAX_ENCRYPTION_KEY) before they get here.
create table if not exists public.tax_profiles (
    roblox_user_id      bigint primary key,
    roblox_username     text,
    form_type           text not null check (form_type in ('W9', 'W8BEN')),
    legal_name          text not null,
    business_name       text,
    tax_classification  text,
    country             text not null,
    address_line1       text,
    address_line2       text,
    city                text,
    region              text,
    postal_code         text,
    tin_encrypted       text,
    tin_last4           text,
    tin_type            text,
    has_dob             boolean not null default false,
    signed_name         text,
    signed_at           timestamptz,
    updated_at          timestamptz not null default now()
);
create index if not exists payment_requests_paid_at_idx on public.payment_requests (paid_at) where paid_at is not null;

-- Game budgets ------------------------------------------------------------------------------
alter table public.games add column if not exists budget_warned_pct integer not null default 0;

-- Two-factor sign-in ------------------------------------------------------------------------
create table if not exists public.user_mfa (
    roblox_user_id      bigint primary key,
    roblox_username     text,
    secret_encrypted    text not null,
    enabled             boolean not null default false,
    enabled_at          timestamptz,
    last_step           bigint not null default -1,
    last_used_at        timestamptz,
    recovery_hashes     jsonb not null default '[]'::jsonb,
    created_at          timestamptz not null default now()
);
alter table public.hr_sessions add column if not exists mfa_pending boolean not null default false;
alter table public.app_settings add column if not exists mfa_required boolean not null default false;
-- Setup wizard and operations ------------------------------------------------------------------
alter table public.app_settings add column if not exists setup_completed_at timestamptz;
alter table public.app_settings add column if not exists setup_completed_by text;
alter table public.app_settings add column if not exists setup_skipped boolean not null default false;

create table if not exists public.error_events (
    id              bigint generated by default as identity primary key,
    fingerprint     text not null unique,
    source          text not null default 'server',
    message         text not null,
    stack           text,
    context         jsonb not null default '{}'::jsonb,
    count           integer not null default 1,
    first_seen_at   timestamptz not null default now(),
    last_seen_at    timestamptz not null default now(),
    resolved_at     timestamptz
);
create index if not exists error_events_last_seen_idx on public.error_events (last_seen_at desc);
-- <<< features schema

-- 3. Keep the database closed to the public key -----------------------------------------------
do $$
declare r record;
begin
    for r in select tablename from pg_tables where schemaname = 'public' loop
        execute format('alter table public.%I enable row level security', r.tablename);
        execute format('revoke all on table public.%I from anon, authenticated', r.tablename);
    end loop;
end $$;

grant usage on schema public to service_role;
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;

commit;

-- Check: should return one row with has_branding = true.
select exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'app_settings' and column_name = 'branding'
) as has_branding;
